class TestDynamicCushionAndFloorBuffer:
    """Stress tests for floor buffer (< $400) boundary conditions and post-payout floor locking."""

    def test_floor_buffer_exact_boundaries(self):
        """Stress-test cushion_floor_buffer = 400.0 at 400.01, 400.00, 399.99, 0.0, and negative."""
        policy = SizingPolicy(
            name="Safe CPPI Test",
            kind="dynamic_cushion",
            tiers=((750.0, 4), (350.0, 3), (-np.inf, 2)),
            cushion_floor_buffer=400.0,
            dynamic_delever_contracts=1,
        )

        # Above buffer: tier contracts apply based on profit
        assert policy.total_micros(profit=500.0, cushion=400.01) == 3
        assert policy.total_micros(profit=800.0, cushion=400.01) == 4
        assert policy.total_micros(profit=100.0, cushion=400.01) == 2

        # Exactly at boundary (400.00): condition is cushion < 400.0, so 400.00 is NOT breached
        assert policy.total_micros(profit=500.0, cushion=400.00) == 3

        # Strictly below buffer (399.99): must immediately de-escalate to 1 micro
        assert policy.total_micros(profit=500.0, cushion=399.99) == 1
        assert policy.total_micros(profit=1000.0, cushion=399.99) == 1
        assert policy.total_micros(profit=0.0, cushion=399.99) == 1
        assert policy.total_micros(profit=0.0, cushion=0.0) == 1
        assert policy.total_micros(profit=-100.0, cushion=-50.0) == 1

        # If cushion is None: defaults to profit-based tiers
        assert policy.total_micros(profit=500.0, cushion=None) == 3

    def test_intraday_multi_trade_cushion_transitions(self):
        """Verify that intraday trades dynamically de-escalate and re-escalate as cushion crosses $400."""
        policy = SizingPolicy(
            name="Safe CPPI Dynamic",
            kind="dynamic_cushion",
            tiers=((750.0, 4), (350.0, 3), (-np.inf, 2)),
            cushion_floor_buffer=400.0,
            dynamic_delever_contracts=1,
        )
        rules = PropRules(start=25000.0, max_dd=1000.0)

        leg1 = Leg(order=0, sym="MNQ", micro="MNQ", per_contract=-100.0, research=-100.0, research_contracts=1, s1_pair=False)
        leg2 = Leg(order=1, sym="MNQ", micro="MNQ", per_contract=250.0, research=250.0, research_contracts=1, s1_pair=False)
        leg3 = Leg(order=2, sym="MGC", micro="MGC", per_contract=100.0, research=100.0, research_contracts=1, s1_pair=False)

        bal = 24420.0
        floor = 24000.0

        # Leg 1
        cushion1 = bal - floor
        assert cushion1 == 420.0
        c1 = leg_contracts(leg1, policy, profit=bal - rules.start, cushion=cushion1)
        assert c1 == 2, f"Expected 2 contracts for cushion={cushion1}, got {c1}"
        pnl1 = leg_pnl(leg1, policy, profit=bal - rules.start, extra_ticks=0.0, cushion=cushion1)
        bal += pnl1
        assert bal == 24220.0

        # Leg 2
        cushion2 = bal - floor
        assert cushion2 == 220.0
        c2 = leg_contracts(leg2, policy, profit=bal - rules.start, cushion=cushion2)
        assert c2 == 1, f"Expected de-escalation to 1 contract for cushion={cushion2}, got {c2}"
        pnl2 = leg_pnl(leg2, policy, profit=bal - rules.start, extra_ticks=0.0, cushion=cushion2)
        bal += pnl2
        assert bal == 24470.0

        # Leg 3
        cushion3 = bal - floor
        assert cushion3 == 470.0
        c3 = leg_contracts(leg3, policy, profit=bal - rules.start, cushion=cushion3)
        assert c3 == 2, f"Expected re-escalation to 2 contracts for cushion={cushion3}, got {c3}"
        pnl3 = leg_pnl(leg3, policy, profit=bal - rules.start, extra_ticks=0.0, cushion=cushion3)
        bal += pnl3
        assert bal == 24670.0

    def test_post_payout_floor_locking_across_5_consecutive_payouts(self):
        """Stress-test floor locking at $25,100 through 5 full funded cycles and verify de-leveraging behavior."""
        rules = PropRules(start=25000.0, max_dd=1000.0, peak_for_lock=26100.0, floor_lock=25100.0)
        funded = FundedRules(
            cycle_sessions=5,
            min_profit_days=3,
            profit_day_threshold=50.0,
            min_payout=300.0,
            max_payout=1000.0,
            payout_fraction=0.50,
            split=0.90,
            max_payouts=5,
            post_payout_floor=25100.0,
        )
        policy = SizingPolicy(
            name="Safe CPPI Funded",
            kind="dynamic_cushion",
            tiers=((750.0, 4), (350.0, 3), (-np.inf, 2)),
            cushion_floor_buffer=400.0,
            dynamic_delever_contracts=1,
        )

        sessions = []
        for cycle in range(5):
            for day in range(5):
                if day < 3:
                    l = Leg(order=0, sym="MNQ", micro="MNQ", per_contract=200.0, research=200.0, research_contracts=1, s1_pair=False)
                    sessions.append([[l]])
                else:
                    sessions.append([])

        res = run_funded(sessions, policy, rules, funded, keep_path=True)

        assert res["status"] == "max_payouts", f"Expected max_payouts, got {res['status']}"
        assert len(res["payouts"]) == 5, f"Expected 5 payouts, got {len(res['payouts'])}"

        floor_path = res["floor_path"]
        assert max(floor_path) == 25100.0, f"Floor should never exceed 25100.0, got {max(floor_path)}"

        first_payout_session = res["payouts"][0][0]
        for s_idx in range(first_payout_session, len(floor_path)):
            assert floor_path[s_idx] == 25100.0, f"Floor at session {s_idx} was {floor_path[s_idx]}, expected 25100.0"

        total_net = sum(p[1] for p in res["payouts"])
        assert total_net > 0.0

    def test_withdrawal_refusal_when_breaching_floor(self):
        """Verify that withdrawal is skipped if bal - wd <= floor, preventing self-liquidation."""
        rules = PropRules(start=25000.0, max_dd=1000.0, floor_lock=25100.0)
        funded = FundedRules(cycle_sessions=5, min_profit_days=3, min_payout=300.0, post_payout_floor=25100.0)

        bal = 25500.0
        floor = 25300.0
        prof = bal - 25000.0  # 500
        wd = prof * 0.5  # 250
        assert not (wd >= 300.0 and bal - wd > floor)


