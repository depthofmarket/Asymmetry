class TestCRNInvariance:
    """Stress tests verifying that CRN strictly isolates sizing differences without MC sampling noise."""

    def test_crn_path_identity_across_grid_points(self, session_legs: list[list[list[Leg]]]):
        """Confirm that precomputed paths generated by run_ratchet_grid_search are strictly identical across policies."""
        n_sims = 100
        seed = 42
        block_size = 10
        horizon = 750
        n_sessions = len(session_legs)

        rng = np.random.default_rng(seed)
        paths_expected = [
            block_bootstrap_sessions(n_sessions, horizon, block_size, rng)
            for _ in range(n_sims)
        ]

        pol_baseline = SizingPolicy("Baseline 350/750", "ratchet", tiers=((750.0, 4), (350.0, 3), (-np.inf, 2)))
        pol_optimal = SizingPolicy("Optimal 200/550", "ratchet", tiers=((550.0, 4), (200.0, 3), (-np.inf, 2)))

        res_baseline = [run_evaluation([session_legs[j] for j in p], pol_baseline) for p in paths_expected]
        res_optimal = [run_evaluation([session_legs[j] for j in p], pol_optimal) for p in paths_expected]

        paired_diffs = []
        for i, (rb, ro) in enumerate(zip(res_baseline, res_optimal)):
            if rb.status == "pass" and ro.status == "pass":
                paired_diffs.append(ro.sessions - rb.sessions)

        paired_diffs = np.array(paired_diffs)
        assert np.mean(paired_diffs) < 0.0, f"Expected optimal to be faster on paired paths, got mean diff {np.mean(paired_diffs)}"

    def test_crn_variance_reduction_factor(self, session_legs: list[list[list[Leg]]]):
        """Quantify the Variance Reduction Ratio (VRR) of CRN vs independent sampling."""
        n_sims = 1000
        seed = 12345
        pol_a = SizingPolicy("Baseline 350/750", "ratchet", tiers=((750.0, 4), (350.0, 3), (-np.inf, 2)))
        pol_b = SizingPolicy("Optimal 200/550", "ratchet", tiers=((550.0, 4), (200.0, 3), (-np.inf, 2)))

        n_sessions = len(session_legs)
        horizon = 750
        block_size = 10

        # CRN: same paths
        rng_crn = np.random.default_rng(seed)
        crn_paths = [block_bootstrap_sessions(n_sessions, horizon, block_size, rng_crn) for _ in range(n_sims)]

        res_a_crn = [run_evaluation([session_legs[j] for j in p], pol_a) for p in crn_paths]
        res_b_crn = [run_evaluation([session_legs[j] for j in p], pol_b) for p in crn_paths]

        pass_a_crn = np.array([r.status == "pass" for r in res_a_crn], dtype=float)
        pass_b_crn = np.array([r.status == "pass" for r in res_b_crn], dtype=float)

        diff_crn = pass_b_crn - pass_a_crn
        var_crn = float(np.var(diff_crn, ddof=1))

        # Independent paths: distinct random draws
        rng_indep_a = np.random.default_rng(seed + 101)
        rng_indep_b = np.random.default_rng(seed + 202)
        paths_a = [block_bootstrap_sessions(n_sessions, horizon, block_size, rng_indep_a) for _ in range(n_sims)]
        paths_b = [block_bootstrap_sessions(n_sessions, horizon, block_size, rng_indep_b) for _ in range(n_sims)]

        pass_a_indep = np.array([run_evaluation([session_legs[j] for j in p], pol_a).status == "pass" for p in paths_a], dtype=float)
        pass_b_indep = np.array([run_evaluation([session_legs[j] for j in p], pol_b).status == "pass" for p in paths_b], dtype=float)

        var_indep = float(np.var(pass_a_indep, ddof=1) + np.var(pass_b_indep, ddof=1))

        corr_pass = np.corrcoef(pass_a_crn, pass_b_crn)[0, 1]
        vrr_pass = var_indep / var_crn if var_crn > 0 else np.inf

        # Strong correlation and VRR on pass/fail status
        assert corr_pass > 0.70, f"Expected pass rate correlation > 0.70, got {corr_pass:.4f}"
        assert vrr_pass > 3.0, f"Expected pass rate VRR > 3.0, got {vrr_pass:.2f}x"

        # Even stronger correlation and VRR on continuous session pass duration
        both_pass_a = []
        both_pass_b = []
        for ra, rb in zip(res_a_crn, res_b_crn):
            if ra.status == "pass" and rb.status == "pass":
                both_pass_a.append(ra.sessions)
                both_pass_b.append(rb.sessions)

        both_pass_a = np.array(both_pass_a)
        both_pass_b = np.array(both_pass_b)
        corr_dur = np.corrcoef(both_pass_a, both_pass_b)[0, 1]
        diff_dur = both_pass_b - both_pass_a
        var_dur_crn = np.var(diff_dur, ddof=1)
        var_dur_indep = np.var(both_pass_a, ddof=1) + np.var(both_pass_b, ddof=1)
        vrr_dur = var_dur_indep / var_dur_crn

        assert corr_dur > 0.95, f"Expected duration correlation > 0.95, got {corr_dur:.4f}"
        assert vrr_dur > 20.0, f"Expected duration VRR > 20.0x, got {vrr_dur:.2f}x"

    def test_crn_funded_transition_identical_accounts(self, session_legs: list[list[list[Leg]]]):
        """Verify that run_funded_transition_experiments feeds the identical passed accounts to all funded policies."""
