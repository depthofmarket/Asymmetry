class TestChronologicalReplay:
    """Stress tests replaying the 1,499 session calendar under Pareto optimal ($200/$550) vs baseline ($350/$750)."""

    def test_chronological_every_start_comparison(self, session_legs: list[list[list[Leg]]], session_calendar: list[str]):
        """Compare all 1,499 possible historical start dates for Pareto optimal vs baseline."""
        pol_baseline = SizingPolicy("Baseline 350/750", "ratchet", tiers=((750.0, 4), (350.0, 3), (-np.inf, 2)))
        pol_optimal = SizingPolicy("Optimal 200/550", "ratchet", tiers=((550.0, 4), (200.0, 3), (-np.inf, 2)))

        res_base = chronological_prop(session_legs, session_calendar, pol_baseline)
        res_opt = chronological_prop(session_legs, session_calendar, pol_optimal)

        df_base = res_base["every_start"]
        df_opt = res_opt["every_start"]

        pass_base = df_base[df_base["status"] == "pass"]
        pass_opt = df_opt[df_opt["status"] == "pass"]

        med_sess_base = float(pass_base["sessions"].median())
        med_sess_opt = float(pass_opt["sessions"].median())
        mean_sess_base = float(pass_base["sessions"].mean())
        mean_sess_opt = float(pass_opt["sessions"].mean())

        pass_rate_base = len(pass_base) / len(df_base) * 100.0
        pass_rate_opt = len(pass_opt) / len(df_opt) * 100.0

        # Optimal compresses median duration significantly: 82.0 vs 95.0 (-13.0 sessions)
        assert med_sess_opt <= med_sess_base, f"Expected optimal median ({med_sess_opt}) <= baseline ({med_sess_base})"
        assert mean_sess_opt <= mean_sess_base, f"Expected optimal mean ({mean_sess_opt}) <= baseline ({mean_sess_base})"
        assert pass_rate_opt >= 75.0, f"Expected chronological pass rate >= 75.0%, got {pass_rate_opt:.2f}%"

    def test_chronological_back_to_back_comparison(self, session_legs: list[list[list[Leg]]], session_calendar: list[str]):
        """Compare sequential back-to-back evaluations across the entire 2021-2026 calendar."""
        pol_baseline = SizingPolicy("Baseline 350/750", "ratchet", tiers=((750.0, 4), (350.0, 3), (-np.inf, 2)))
        pol_optimal = SizingPolicy("Optimal 200/550", "ratchet", tiers=((550.0, 4), (200.0, 3), (-np.inf, 2)))

        res_base = chronological_prop(session_legs, session_calendar, pol_baseline)["back_to_back"]
        res_opt = chronological_prop(session_legs, session_calendar, pol_optimal)["back_to_back"]

        passes_base = (res_base["status"] == "pass").sum()
        passes_opt = (res_opt["status"] == "pass").sum()

        avg_dur_base = res_base[res_base["status"] == "pass"]["sessions"].mean()
        avg_dur_opt = res_opt[res_opt["status"] == "pass"]["sessions"].mean()

        assert passes_base >= 5, f"Expected at least 5 passed attempts in baseline, got {passes_base}"
        assert passes_opt >= 5, f"Expected at least 5 passed attempts in optimal, got {passes_opt}"
        assert avg_dur_opt <= avg_dur_base, f"Expected optimal avg pass duration ({avg_dur_opt}) <= baseline ({avg_dur_base})"

    def test_continuous_drawdown_stress(self, session_legs: list[list[list[Leg]]]):
        """Simulate continuous multi-year equity curve to compare maximum dollar drawdown between policies."""
        pol_baseline = SizingPolicy("Baseline 350/750", "ratchet", tiers=((750.0, 4), (350.0, 3), (-np.inf, 2)))
        pol_optimal = SizingPolicy("Optimal 200/550", "ratchet", tiers=((550.0, 4), (200.0, 3), (-np.inf, 2)))

        def simulate_continuous_equity(policy: SizingPolicy):
            bal = 25000.0
            peak = 25000.0
            max_dd = 0.0
            equity = [bal]
            for s in session_legs:
                for grp in s:
                    prof_now = bal - 25000.0
                    pnl = sum(leg_pnl(l, policy, prof_now, extra_ticks=0.0) for l in grp)
                    bal += pnl
                equity.append(bal)
                if bal > peak:
                    peak = bal
                dd = peak - bal
                if dd > max_dd:
                    max_dd = dd
            return np.array(equity), max_dd, bal - 25000.0

        eq_base, dd_base, net_base = simulate_continuous_equity(pol_baseline)
        eq_opt, dd_opt, net_opt = simulate_continuous_equity(pol_optimal)

        # Both policies generate > $20,000 net profit across 1,499 sessions
        assert net_base > 20000.0, f"Expected baseline net > 20000, got {net_base}"
        assert net_opt > 20000.0, f"Expected optimal net > 20000, got {net_opt}"
        # Continuous profit difference is within 0.5% ($20,710.84 vs $20,769.42)
        assert abs(net_opt - net_base) / net_base < 0.005
        # Max continuous dollar drawdown is identical to within $0.01 ($3,031.58)
        assert abs(dd_opt - dd_base) < 0.01
